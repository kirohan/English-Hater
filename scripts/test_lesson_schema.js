const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(new URL('../data/lesson-schema.js', `file://${__filename}`), 'utf8');
const context = { window: {} };
vm.runInNewContext(source, context, { filename: 'lesson-schema.js' });
const schema = context.window.EHLessonSchema;
assert.ok(schema, 'schema helper should be exposed');
const fixture = JSON.parse(fs.readFileSync(new URL('../lesson-import-template.json', `file://${__filename}`), 'utf8'));
const result = schema.validatePackage(fixture);
assert.equal(JSON.stringify(result.errors), '[]', 'the bundled JSON template should validate');
const normalized = schema.normalizeLesson(result.lessons[0]);
assert.equal(normalized.schema_version, '1.0.0');
assert.equal(normalized.track, 'ssc');
assert.equal(normalized.topic, 'article');
assert.equal(normalized.sections.length, 5);
assert.equal(normalized.review_status, 'review');
assert.equal(normalized.published, false, 'new/unapproved lessons must not publish');
const invalid = schema.validatePackage({ id: 'bad', track: 'unknown', topic: 'Bad Topic', title: '', sections: [] });
assert.ok(invalid.errors.length >= 3, 'invalid track, topic and title should be rejected');
const duplicate = schema.validatePackage({ lessons: [result.lessons[0], result.lessons[0]] });
assert.ok(duplicate.errors.some(x => x.includes('Duplicate lesson id')));
console.log('Structured lesson schema tests passed.');
