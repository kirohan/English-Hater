const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('data/lesson-schema.js', 'utf8');
const context = { window: {} };
vm.runInNewContext(source, context, { filename: 'lesson-schema.js' });
const schema = context.window.EHLessonSchema;
assert.ok(schema, 'schema helper should be exposed');
const template = JSON.parse(fs.readFileSync('lesson-import-template.json', 'utf8'));
assert.equal(schema.validatePackage(template).errors.length, 0, 'generic lesson template should validate');
const articlePackage = JSON.parse(fs.readFileSync('content/articles/lesson-ssc-article.json', 'utf8'));
const result = schema.validatePackage(articlePackage);
assert.equal(JSON.stringify(result.errors), '[]', 'source-based Article lesson should validate');
assert.equal(result.lessons.length, 1);
const normalized = schema.normalizeLesson(result.lessons[0]);
assert.equal(normalized.schema_version, '1.0.0');
assert.equal(normalized.track, 'ssc');
assert.equal(normalized.topic, 'article');
assert.equal(normalized.sections.length, 16);
assert.equal(normalized.review_status, 'review');
assert.equal(normalized.published, false, 'unapproved lesson must not publish');
assert.equal(normalized.source_reference.printed_pages, '218–241', 'source metadata should survive normalization');
const invalid = schema.validatePackage({ id: 'bad', track: 'unknown', topic: 'Bad Topic', title: '', sections: [] });
assert.ok(invalid.errors.length >= 3, 'invalid track, topic and title should be rejected');
const duplicate = schema.validatePackage({ lessons: [result.lessons[0], result.lessons[0]] });
assert.ok(duplicate.errors.some(x => x.includes('Duplicate lesson id')));
console.log('Structured lesson schema tests passed (template + source-based Article).');
